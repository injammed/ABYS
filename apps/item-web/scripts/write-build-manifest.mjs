import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDir, "..");

const productionCommit = process.env.BUILD_COMMIT_SHA || process.env.GITHUB_SHA || "development";
const deployedAt = process.env.BUILD_DEPLOYED_AT || new Date().toISOString();
const steelFold = Number.parseInt(process.env.STEEL_FOLD || "3", 10);

if (!Number.isFinite(steelFold) || steelFold < 0) {
  throw new Error("STEEL_FOLD must be a non-negative integer.");
}

const manifest = {
  product: "aetimm.com",
  repository: "injammed/ABYS",
  runtimePath: "apps/item-web",
  buildMode: "human-directed-ai-assisted",
  productionCommit,
  deployedAt,
  steelFold,
  openCompletionIssue: 39,
};

const publicPath = resolve(appRoot, "public", "build-manifest.json");
const modulePath = resolve(appRoot, "lib", "generated-build-manifest.ts");
const moduleSource = `// Generated by scripts/write-build-manifest.mjs before every production build.
export type BuildManifest = {
  product: string;
  repository: string;
  runtimePath: string;
  buildMode: "human-directed-ai-assisted";
  productionCommit: string;
  deployedAt: string;
  steelFold: number;
  openCompletionIssue: number;
};

export const buildManifest: BuildManifest = ${JSON.stringify(manifest, null, 2)};
`;

await mkdir(dirname(publicPath), { recursive: true });
await mkdir(dirname(modulePath), { recursive: true });

await Promise.all([
  writeFile(publicPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8"),
  writeFile(modulePath, moduleSource, "utf8"),
]);

console.log(`Build manifest written for ${productionCommit.slice(0, 12)} at ${deployedAt}.`);
